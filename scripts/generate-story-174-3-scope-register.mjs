import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const OUTPUT =
  '_bmad-output/implementation-artifacts/174-3-expanded-scope-register.md'

const gitLines = args =>
  execFileSync('git', args, { encoding: 'utf8' })
    .split(/\r?\n/)
    .map(line => line.trim())
    .filter(Boolean)

function classification(path) {
  if (path === OUTPUT || path.endsWith('174-3-fe-complete-accessibility-responsive-theme-and-visual-verification.md')) {
    return 'delivery-record'
  }
  if (path === '.omx/plans/174.3-complete-accessibility-responsive-theme-and-visual-verification.md') {
    return 'remediation-plan'
  }
  if (
    path.startsWith('e2e/fixtures/story-174-3') ||
    path.startsWith('e2e/support/story-174-3') ||
    path.startsWith('e2e/story-174-3') ||
    path === 'e2e/shadcn-migration-visual-accessibility.spec.ts' ||
    path.includes('story-174-3')
  ) {
    return 'story-evidence'
  }
  if (path.startsWith('e2e/')) return 'owner-browser-evidence'
  if (
    path.startsWith('src/components/ui/') ||
    path === 'src/app/(dashboard)/layout.tsx' ||
    /src\/components\/custom\/(?:Sidebar|Navbar)/.test(path)
  ) {
    return 'foundation-appshell-coordination'
  }
  if (/^src\/(?:hooks|types|lib)\//.test(path)) return 'shared-owner-remediation'
  if (path.startsWith('src/')) return 'route-owner-remediation'
  if (path.startsWith('scripts/')) return 'repository-validation'
  return 'story-support'
}

const categoryRecords = {
  'delivery-record': ['174.3', 'Authoritative Story evidence and exact lifecycle handoff.'],
  'remediation-plan': ['174.3', 'Accepted review findings, immutable three-review gate, and cleanup protocol.'],
  'story-evidence': ['174.3', 'Executable route/state/surface/manifest evidence owned by this assurance Story.'],
  'owner-browser-evidence': ['route owner + 174.3', 'Coordinated deterministic browser proof for an owner route.'],
  'foundation-appshell-coordination': ['166/167 owner + 174.3', 'Narrow accepted accessibility repair discovered by the canonical matrix.'],
  'shared-owner-remediation': ['named shared owner + 174.3', 'Narrow contract-preserving repair with focused regression evidence.'],
  'route-owner-remediation': ['ledger route owner + 174.3', 'Accepted route-specific accessibility/responsive/data-semantics repair.'],
  'repository-validation': ['174.3', 'Relocatable fail-closed local validation required by the Story evidence pipeline.'],
  'story-support': ['174.3', 'Direct support file required by the recorded Story validation.'],
}

const paths = new Set([
  ...gitLines(['diff', '--name-only', '--diff-filter=ACMR', 'origin/main']),
  ...gitLines(['ls-files', '--others', '--exclude-standard']),
  OUTPUT,
  'scripts/generate-story-174-3-scope-register.mjs',
])
const sorted = [...paths].sort()
const counts = new Map()
for (const path of sorted) {
  const category = classification(path)
  counts.set(category, (counts.get(category) ?? 0) + 1)
}

const lines = [
  '# Story 174.3 Expanded Scope and Owner-Coordination Register',
  '',
  '> Generated by `scripts/generate-story-174-3-scope-register.mjs` from the exact',
  '> `origin/main` comparison plus current untracked Story files. Regenerate before freeze;',
  '> any path drift is a review blocker.',
  '',
  `**Files:** ${sorted.length}`,
  '',
  '## Coordination classes',
  '',
  '| Class | Files | Canonical owner | Admission rationale |',
  '| --- | ---: | --- | --- |',
  ...[...counts.entries()].sort().map(([category, count]) => {
    const [owner, rationale] = categoryRecords[category]
    return `| ${category} | ${count} | ${owner} | ${rationale} |`
  }),
  '',
  'All product/shared entries are coordinated repairs discovered by executable Story 174.3',
  'verification. They preserve API/query/calculation/navigation semantics, add no dependency,',
  'and require their focused owner tests plus the complete Story matrix. The user explicitly',
  'authorized the foundation hotfix and the Story 174.3 completion/PR lifecycle. No backend,',
  'deployment, production, force-push, or direct-`main` operation is admitted.',
  '',
  '## Exact file manifest',
  '',
  '| Path | Coordination class |',
  '| --- | --- |',
  ...sorted.map(path => `| \`${path.replaceAll('|', '\\|')}\` | ${classification(path)} |`),
  '',
]

writeFileSync(OUTPUT, lines.join('\n'))
console.log(`Story 174.3 scope register: ${sorted.length} files -> ${OUTPUT}`)
